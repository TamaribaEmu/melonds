#!/bin/sh
# Writes ../src/FreeBIOS.h, the BIOS melonDS falls back on, from the two OpenDS images.
set -eu
cd "$(dirname "$0")"
out=../src/FreeBIOS.h
array() {
    printf 'unsigned char %s[] = {\n' "$1"
    od -An -v -tx1 "$2" | sed 's/ \([0-9a-f][0-9a-f]\)/ 0x\1,/g; s/^ */  /; s/ *$//'
    printf '};\nunsigned int %s_len = %s;\n' "$1" "$(wc -c < "$2" | tr -d ' ')"
}
{
    printf '/*  OpenDS, an open-source Nintendo DS ARM7/ARM9 BIOS replacement\n'
    printf '    (freebios/opends_bios.S; generated by freebios/make-header.sh).\n\n'
    sed 's/^/    /; s/ *$//' LICENSE
    printf '\n    The ARM7 image leaves the DS KEY1 table at 0x30 empty: it holds no Nintendo\n'
    printf '    data. A frontend may supply the table (melonds_set_key1, libretro.cpp).\n*/\n\n'
    printf '#ifndef FREEBIOS_H\n#define FREEBIOS_H\n\n'
    array bios_arm7_bin opends_bios7.bin
    printf '\n'
    array bios_arm9_bin opends_bios9.bin
    printf '\n#endif // FREEBIOS_H\n'
} > "$out"
echo "Wrote $out"
